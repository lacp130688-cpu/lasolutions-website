-- ------------------------------------------------------------
-- 1. PRODUCTOS
-- ------------------------------------------------------------
create table if not exists public.products (
  id integer generated by default as identity primary key,
  name text not null,
  category text not null check (category in ('Escritorio', 'Gaming', 'Laptop')),
  brand text not null default 'laSolutions',
  price numeric(10, 2) not null check (price >= 0),
  original_price numeric(10, 2),
  description text not null default '',
  specs jsonb not null default '[]'::jsonb,
  image text not null default 'assets/placeholder.svg',
  featured boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 2. PROMOCIONES
-- ------------------------------------------------------------
create table if not exists public.promotions (
  id integer generated by default as identity primary key,
  product_id integer not null references public.products (id) on delete cascade,
  discount integer not null check (discount > 0 and discount < 100),
  sale_price numeric(10, 2) not null check (sale_price >= 0),
  label text not null default 'Oferta',
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 3. MENSAJES DE CONTACTO
-- ------------------------------------------------------------
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text not null,
  message text not null,
  created_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 4. INDICES
-- ------------------------------------------------------------
create index if not exists idx_products_category on public.products (category);
create index if not exists idx_products_active on public.products (active) where active = true;
create index if not exists idx_promotions_active on public.promotions (active) where active = true;
create index if not exists idx_promotions_product on public.promotions (product_id);
create index if not exists idx_contact_messages_created on public.contact_messages (created_at desc);

