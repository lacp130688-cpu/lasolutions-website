-- ------------------------------------------------------------
-- 7. ROW LEVEL SECURITY (RLS)
-- ------------------------------------------------------------
alter table public.products         enable row level security;
alter table public.promotions       enable row level security;
alter table public.contact_messages enable row level security;

-- Productos y promociones: lectura publica (anon), escritura solo owner
create policy "products public read"
  on public.products for select
  using (true);

create policy "products owner write"
  on public.products for all
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

create policy "promotions public read"
  on public.promotions for select
  using (true);

create policy "promotions owner write"
  on public.promotions for all
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

-- Contacto: cualquiera puede insertar (anon), solo owner lee
create policy "contact_messages public insert"
  on public.contact_messages for insert
  with check (true);

create policy "contact_messages owner read"
  on public.contact_messages for select
  using (auth.role() = 'authenticated');

-- ------------------------------------------------------------
-- 8. FUNCION AUXILIAR: datos de catalogo con promo aplicada
-- ------------------------------------------------------------
create or replace function public.get_products_with_promo()
returns json
language sql
stable
as $$
  select json_agg(
    json_build_object(
      'id', p.id,
      'name', p.name,
      'category', p.category,
      'brand', p.brand,
      'price', coalesce(pr.sale_price, p.price),
      'originalPrice', p.price,
      'description', p.description,
      'specs', p.specs,
      'image', p.image,
      'onSale', (pr.sale_price is not null and pr.sale_price < p.price),
      'discount', pr.discount
    )
  )
  from public.products p
  left join public.promotions pr
    on pr.product_id = p.id
   and pr.active = true
   and (pr.starts_at is null or pr.starts_at <= now())
   and (pr.ends_at is null or pr.ends_at > now())
  where p.active = true
  order by p.id;
$$;